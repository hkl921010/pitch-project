function views(base: number, trend: number, seed: number): number[] {
  return Array.from({ length: 14 }, (_, i) => {
    const wobble = Math.round(Math.sin(i * 1.7 + seed) * base * 0.25);
    return Math.max(0, Math.round(base + trend * i + wobble));
  });
}

function sources(total: number, weights: Partial<Record<TrafficSource, number>>): Record<TrafficSource, number> {
  const all: TrafficSource[] = ["wechat", "moments", "poster", "discover", "demoday", "article", "direct"];
  const sum = all.reduce((s, k) => s + (weights[k] ?? 1), 0);
  return Object.fromEntries(all.map((k) => [k, Math.round((total * (weights[k] ?? 1)) / sum)])) as Record<TrafficSource, number>;
}

