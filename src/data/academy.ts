/** 往期嘉宾完整名单：代表导师、创投嘉宾、到场投资人，按出现顺序去重。 */
export function guestRoster(): AcademyPerson[] {
  const seen = new Set<string>();
  const list: AcademyPerson[] = [];
  const push = (person: AcademyPerson) => {
    if (seen.has(person.name)) return;
    seen.add(person.name);
    list.push(person);
  };
  for (const group of GUEST_GROUPS) for (const person of group.people) push(person);
  for (const person of MORE_GUESTS) push(person);
  for (const person of INVESTORS) push(person);
  return list;
}
